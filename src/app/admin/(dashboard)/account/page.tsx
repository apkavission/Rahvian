import type { Metadata } from "next";
import { ADMIN_NAV_ITEMS } from "@/components/admin/nav";
import { resolveMenu } from "@/lib/auth/menu";
import { requireStaff } from "@/lib/auth/session";
import { PasswordForm } from "./password-form";

export const metadata: Metadata = {
  title: "Your account",
  robots: { index: false, follow: false, nocache: true },
};

/**
 * Your own account.
 *
 * Deliberately outside the menu system: `requireStaff()` rather than
 * `requireMenu()`, because everybody who can sign in must be able to change
 * their own password, and a screen that can be taken away from somebody by an
 * owner is not that.
 *
 * It shows what you are and what you reach, and lets you change one thing. The
 * rest — your role, your menu, whether you are blocked — is somebody else's
 * decision by design, and saying so plainly is better than offering controls
 * that refuse.
 */
export default async function AccountScreen() {
  const { profile, email, role } = await requireStaff();

  const menu = resolveMenu(profile, role);
  const reachable = ADMIN_NAV_ITEMS.filter((item) => menu.has(item.key));

  return (
    <div className="mx-auto w-full max-w-3xl">
      <header>
        <h1 className="font-display text-2xl font-semibold">Your account</h1>
        <p className="measure mt-2 text-sm leading-relaxed text-text-muted">
          Your own details, and the one thing here you can change yourself.
        </p>
      </header>

      <div className="mt-10 space-y-6">
        <section className="surface-raised rounded-2xl border border-border p-6">
          <h2 className="font-display text-base font-semibold">Who you are</h2>

          <dl className="mt-5 grid gap-x-6 gap-y-4 sm:grid-cols-2">
            <div>
              <dt className="font-mono text-[0.6rem] uppercase tracking-[0.14em] text-text-subtle">
                Name
              </dt>
              <dd className="mt-1 text-sm">{profile.full_name || "Not set"}</dd>
            </div>
            <div className="min-w-0">
              <dt className="font-mono text-[0.6rem] uppercase tracking-[0.14em] text-text-subtle">
                Email
              </dt>
              <dd className="mt-1 truncate text-sm">{email ?? "Not available"}</dd>
            </div>
            <div className="sm:col-span-2">
              <dt className="font-mono text-[0.6rem] uppercase tracking-[0.14em] text-text-subtle">
                Role
              </dt>
              <dd className="mt-1 text-sm">
                <span className="font-medium">{role.label}</span>
                {role.description && (
                  <span className="measure mt-1 block text-text-muted">
                    {role.description}
                  </span>
                )}
              </dd>
            </div>
          </dl>

          <div className="mt-6 border-t border-border pt-5">
            <p className="font-mono text-[0.6rem] uppercase tracking-[0.14em] text-text-subtle">
              What you can reach
            </p>
            <ul className="mt-2 flex flex-wrap gap-1.5">
              {reachable.map((item) => (
                <li
                  key={item.key}
                  className="rounded-full bg-surface-2 px-3 py-1 text-xs text-text-muted ring-1 ring-border"
                >
                  {item.label}
                </li>
              ))}
            </ul>
            <p className="measure mt-3 text-sm leading-relaxed text-text-muted">
              Your name, your role and this list are an owner&rsquo;s to change,
              not yours — which is what makes them worth trusting.
            </p>
          </div>
        </section>

        <section className="surface-raised rounded-2xl border border-border p-6">
          <h2 className="font-display text-base font-semibold">Password</h2>
          <p className="measure mt-2 text-sm leading-relaxed text-text-muted">
            If you are still using the one you were emailed, change it now. It
            was generated by a machine and passed through a mail server, and it
            has done its job the moment you are in.
          </p>

          <div className="mt-6">
            <PasswordForm />
          </div>
        </section>
      </div>
    </div>
  );
}
