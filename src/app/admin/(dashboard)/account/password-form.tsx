"use client";

import { useActionState } from "react";
import { BrandSpinner } from "@/components/brand/brand-loader";
import { useBusyWhile } from "@/components/forms/use-busy-while";
import { useFormToast } from "@/components/forms/use-form-toast";
import { Button } from "@/components/ui/button";
import { Field, FIELD } from "@/components/ui/field";
import { changeOwnPassword } from "@/lib/actions/users";
import { initialRecordState } from "@/lib/validation/records";

/**
 * Change your own password.
 *
 * The one screen in the panel that is nobody else's business. Everybody who can
 * sign in reaches it, whatever their role — the password you were emailed was
 * generated by a machine and known, briefly, to a mail server, and the first
 * thing anybody should do with it is replace it.
 *
 * The current password is asked for even though the session already proves who
 * is asking, because it proves something else: that the person at the keyboard
 * is the account holder rather than whoever found the laptop unlocked.
 *
 * `autoComplete` is set precisely rather than switched off. A password manager
 * that understands this form will offer to generate and then store the new
 * password, which is a better outcome than anything the form could do itself.
 */
export function PasswordForm() {
  const [state, formAction, pending] = useActionState(
    changeOwnPassword,
    initialRecordState,
  );

  useBusyWhile(pending, "Changing your password");
  useFormToast(state, {
    successTitle: "Password changed",
    errorTitle: "Could not change it",
  });

  return (
    <form
      action={formAction}
      className="space-y-5"
      // Remounted on success, so the three boxes are empty afterwards rather
      // than holding the password that was just set.
      key={state.status === "success" ? "done" : "editing"}
    >
      <Field
        label="Current password"
        required
        error={state.fieldErrors?.current}
      >
        {(id, describedBy) => (
          <input
            id={id}
            name="current"
            type="password"
            required
            autoComplete="current-password"
            aria-describedby={describedBy}
            className={FIELD}
          />
        )}
      </Field>

      <Field
        label="New password"
        required
        hint="At least 12 characters. Length is what makes a password hard to guess — a long phrase beats a short puzzle."
        error={state.fieldErrors?.next}
      >
        {(id, describedBy) => (
          <input
            id={id}
            name="next"
            type="password"
            required
            minLength={12}
            autoComplete="new-password"
            aria-describedby={describedBy}
            className={FIELD}
          />
        )}
      </Field>

      <Field label="New password again" required error={state.fieldErrors?.confirm}>
        {(id, describedBy) => (
          <input
            id={id}
            name="confirm"
            type="password"
            required
            autoComplete="new-password"
            aria-describedby={describedBy}
            className={FIELD}
          />
        )}
      </Field>

      {state.status === "error" && !state.fieldErrors ? (
        <p role="alert" className="text-sm text-danger">
          {state.message}
        </p>
      ) : null}

      <Button type="submit" disabled={pending}>
        {pending ? (
          <>
            <BrandSpinner />
            Changing
          </>
        ) : (
          "Change password"
        )}
      </Button>
    </form>
  );
}
